// Split a backend field name into human tokens.
//   "ApproveTime"      → ["Approve", "Time"]
//   "APIKey"           → ["API", "Key"]
//   "phone_number"     → ["phone", "number"]
//   "ID"               → ["ID"]
//   "PasswordExpireAt" → ["Password", "Expire", "At"]
function tokenize(key) {
  return String(key)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .split(/[_\s\-]+/)
    .filter(Boolean);
}

function smartHeader(key, locale) {
  const tokens = tokenize(key);
  if (locale === "zh") {
    const dictZh = tokenDict.zh;
    return tokens.map((tok) => {
      const k = tok.toLowerCase();
      if (Object.prototype.hasOwnProperty.call(dictZh, k)) return dictZh[k];
      return tok; // unknown token — keep original casing
    }).join("");
  }
  // English: title-case each token, preserve all-caps abbreviations.
  return tokens.map((tok) =>
    /^[A-Z0-9]+$/.test(tok)
      ? tok
      : tok.charAt(0).toUpperCase() + tok.slice(1).toLowerCase()
  ).join(" ");
}

let current = readStored();
const listeners = new Set();

function readStored() {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v && SUPPORTED.includes(v)) return v;
  } catch {/* localStorage may be blocked */}
  return DEFAULT_LOCALE;
}

function writeStored(v) {
  try { localStorage.setItem(STORAGE_KEY, v); } catch {/* ignore */}
}

export function getLocale() {
  return current;
}

export function setLocale(next) {
  if (!SUPPORTED.includes(next) || next === current) return;
  current = next;
  writeStored(next);
  if (typeof document !== "undefined") {
    document.documentElement.lang = next === "en" ? "en" : "zh-CN";
  }
  for (const fn of listeners) {
    try { fn(next); } catch {/* ignore one bad subscriber */}
  }
}

export function toggleLocale() {
  setLocale(current === "zh" ? "en" : "zh");
}

export function onLocaleChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function format(str, params) {
  if (!params || typeof str !== "string") return str;
  return str.replace(/\{(\w+)\}/g, (_, k) =>
    params[k] != null ? String(params[k]) : `{${k}}`);
}

export function t(key, params) {
  const table = dict[current] || dict[DEFAULT_LOCALE];
  const raw = table[key];
  if (raw == null) {
    // Unknown key — fall back to other locale, then to the key itself.
    const alt = (dict[DEFAULT_LOCALE] || {})[key];
    return format(alt != null ? alt : key, params);
  }
  return format(raw, params);
}

export function tHeader(key, fallback) {
  const table = headerDict[current] || headerDict[DEFAULT_LOCALE];
  if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
  if (fallback != null) return fallback;
  // Smart fallback — tokenize the field name and translate token-by-token.
  return smartHeader(key, current);
}

